import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = (path) => readFileSync(resolve(root, path), 'utf8');
export const palette = JSON.parse(read('Resources/Private/Palettes/catppuccin.json'));
export const states = {
    primary: 'mauve', secondary: 'subtext0', info: 'sapphire',
    success: 'green', warning: 'yellow', danger: 'red', notice: 'overlay2',
};

export function contrast(first, second) {
    const luminance = (hex) => hex.match(/[a-f\d]{2}/gi)
        .map((component) => parseInt(component, 16) / 255)
        .map((value) => value <= 0.04045 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4)
        .reduce((sum, value, index) => sum + value * [0.2126, 0.7152, 0.0722][index], 0);
    const a = luminance(first);
    const b = luminance(second);
    return (Math.max(a, b) + 0.05) / (Math.min(a, b) + 0.05);
}

function mix(first, second, amount) {
    const channels = (hex) => hex.match(/[a-f\d]{2}/gi).map((part) => parseInt(part, 16));
    const a = channels(first);
    const b = channels(second);
    return '#' + a.map((value, i) => Math.round(value * (1 - amount) + b[i] * amount)
        .toString(16).padStart(2, '0')).join('');
}

// Keep exact palette colours where readable. Darken low-contrast Latte accents
// towards its text colour when used as text or a solid button background.
export function accessiblePair(colors, color) {
    let bg = colors[color];
    const candidates = ['base', 'text', 'crust'];
    let on = candidates.toSorted((a, b) => contrast(colors[b], bg) - contrast(colors[a], bg))[0];
    if (contrast(colors[on], bg) < 4.5) {
        on = 'base';
        for (let amount = 0.01; amount <= 1; amount += 0.01) {
            bg = mix(colors[color], colors.text, amount);
            if (contrast(colors[on], bg) >= 4.5) break;
        }
    }
    let readable = colors[color];
    for (let amount = 0.01; contrast(readable, colors.base) < 4.5 && amount <= 1; amount += 0.01) {
        readable = mix(colors[color], colors.text, amount);
    }
    const foreground = colors[on];
    // Move interaction backgrounds away from the foreground to retain contrast.
    const target = contrast(foreground, '#000000') > contrast(foreground, '#ffffff') ? '#000000' : '#ffffff';
    return { bg, on: foreground, readable, hover: mix(bg, target, 0.08), focus: mix(bg, target, 0.12) };
}

export function build() {
    let css = '/* Catppuccin for TYPO3 v14. Generated by Build/build.mjs; do not edit.\n'
        + ' * Palette: (c) 2021 Catppuccin, MIT; see Resources/Private/Palettes/LICENSE.\n'
        + ' * Integration: GPL-2.0-only. */\n\n';
    const selectors = [];
    for (const [id, flavour] of Object.entries(palette.flavours)) {
        const selector = `:root[data-theme="catppuccin-${id}"]`;
        selectors.push(selector);
        // Specificity overrides Core's [data-color-scheme], including auto.
        css += `${selector} {\n    color-scheme: only ${flavour.dark ? 'dark' : 'light'};\n`;
        for (const [name, hex] of Object.entries(flavour.colors)) {
            css += `    --ctp-${name}: ${hex};\n`;
        }
        // Tree highlights and .text-highlight must both work with normal text.
        css += `    --ctp-highlight-bg: ${mix(flavour.colors.yellow, flavour.colors.base, 0.8)};\n`;
        for (const [state, color] of Object.entries(states)) {
            const pair = accessiblePair(flavour.colors, color);
            css += `    --ctp-state-${state}: ${pair.bg};\n`;
            css += `    --ctp-hover-${state}: ${pair.hover};\n`;
            css += `    --ctp-focus-${state}: ${pair.focus};\n`;
            css += `    --ctp-on-${state}: ${pair.on};\n`;
            css += `    --ctp-readable-${state}: ${pair.readable};\n`;
        }
        css += '}\n\n';
    }
    css += selectors.join(',\n') + ' {\n' + read('Build/tokens.css');
    for (const [state, color] of Object.entries(states)) {
        css += `\n    /* ${state} */\n`;
        const vars = {
            [`token-color-${state}-base`]: `var(--ctp-${color})`,
            [`typo3-text-color-${state}`]: `var(--ctp-readable-${state})`,
            [`typo3-status-indicator-${state}-color`]: `var(--ctp-readable-${state})`,
            [`typo3-surface-${state}`]: `var(--ctp-state-${state})`,
            [`typo3-surface-${state}-text`]: `var(--ctp-on-${state})`,
            [`typo3-surface-container-${state}`]: `color-mix(in srgb, var(--ctp-base), var(--ctp-${color}) 12%)`,
            [`typo3-surface-container-${state}-text`]: 'var(--ctp-text)',
            [`typo3-state-${state}-color`]: `var(--ctp-on-${state})`,
            [`typo3-state-${state}-bg`]: `var(--ctp-state-${state})`,
            [`typo3-state-${state}-border-color`]: `var(--ctp-state-${state})`,
        };
        for (const interaction of ['hover', 'focus']) {
            vars[`typo3-state-${state}-${interaction}-color`] = `var(--ctp-on-${state})`;
            vars[`typo3-state-${state}-${interaction}-bg`] = `var(--ctp-${interaction}-${state})`;
            vars[`typo3-state-${state}-${interaction}-border-color`] = `var(--ctp-state-${state})`;
        }
        for (const part of ['color', 'bg', 'border-color']) {
            vars[`typo3-state-${state}-disabled-${part}`] = `var(--typo3-state-${state}-${part})`;
        }
        for (const [name, value] of Object.entries(vars)) css += `    --${name}: ${value};\n`;
    }
    return css + '}\n';
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const target = 'Resources/Public/Css/catppuccin.css';
    if (process.argv.includes('--check')) {
        if (read(target) !== build()) throw new Error('CSS is outdated. Run node Build/build.mjs.');
        console.log('Generated CSS is up to date.');
    } else {
        writeFileSync(resolve(root, target), build());
        console.log(`Generated ${target}`);
    }
}
